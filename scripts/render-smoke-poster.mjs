#!/usr/bin/env node
/* Renders the smoke backdrop's first frame (time 0, pointer centred) into
   public/smoke-poster.{avif,webp}, and records the shader fingerprint it was
   rendered from in src/lib/smoke-poster.ts.

   The poster is what every device shows before the live WebGL field fades in
   over it, and what devices that can't run the shader keep, so it has to match
   the shader exactly. Re-run this whenever SMOKE_FRAG, SMOKE_VERT or the hash
   LUT in src/lib/portfolio-webgl.ts change (a unit test fails until you do):

     npm i --no-save playwright sharp
     node scripts/render-smoke-poster.mjs

   It renders through the production code path (three.js + createSmokeMaterial,
   served by Vite) in headless Chromium on SwiftShader, which matches GPUs to
   within 1/255 thanks to the exact hash LUT. */

import { writeFile, rm, stat } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import { createServer } from 'vite';
import { chromium } from 'playwright';
import sharp from 'sharp';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

/* 2.4:1 covers every screen up to 21:9. object-fit: cover then scales it by
   height, centred, exactly as the shader frames the field (p is normalised by
   the viewport height). 480 rows is the live renderer's own top budget, so the
   poster is as detailed as the canvas that replaces it. */
const WIDTH = 1152;
const HEIGHT = 480;

const PAGE = 'smoke-poster.tmp.html';
const html = `<!doctype html><meta charset="utf-8">
<script type="module">
  import { Mesh, OrthographicCamera, PlaneGeometry, Scene, WebGLRenderer } from 'three';
  import { createSmokeMaterial, smokeFingerprint } from '/src/lib/portfolio-webgl.ts';
  window.renderPoster = (w, h) => {
    const renderer = new WebGLRenderer({ antialias: false, alpha: false, preserveDrawingBuffer: true });
    renderer.setPixelRatio(1);
    renderer.setSize(w, h, false);
    const material = createSmokeMaterial();
    renderer.getDrawingBufferSize(material.uniforms.uRes.value);
    const scene = new Scene();
    scene.add(new Mesh(new PlaneGeometry(2, 2), material));
    renderer.render(scene, new OrthographicCamera(-1, 1, 1, -1, 0, 1));
    const out = document.createElement('canvas');
    out.width = w;
    out.height = h;
    out.getContext('2d').drawImage(renderer.domElement, 0, 0);
    return { png: out.toDataURL('image/png'), fingerprint: smokeFingerprint() };
  };
  window.posterReady = true;
</script>`;

await writeFile(resolve(root, PAGE), html);
const server = await createServer({ root, logLevel: 'error', server: { port: 0 } });
let browser;
try {
  await server.listen();
  const url = server.resolvedUrls.local[0] + PAGE;
  browser = await chromium.launch({
    args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'],
  });
  const page = await browser.newPage();
  page.on('pageerror', (e) => console.error(e));
  await page.goto(url);
  await page.waitForFunction(() => window.posterReady === true);
  const { png, fingerprint } = await page.evaluate(([w, h]) => window.renderPoster(w, h), [WIDTH, HEIGHT]);
  const source = Buffer.from(png.split(',')[1], 'base64');
  // Optional: keep the lossless render, e.g. to compare encoder settings.
  if (process.env.POSTER_PNG) await writeFile(process.env.POSTER_PNG, source);

  /* Dark, smooth gradients show coding artefacts easily. AVIF q90 4:4:4 keeps
     the wisps intact (lower qualities soften them) in ~10 KB; WebP is only
     fetched by browsers without AVIF, which are also the likeliest to show the
     poster for good, so it's lossless rather than blocky. */
  const avif = await sharp(source).avif({ quality: 90, effort: 9, chromaSubsampling: '4:4:4' }).toBuffer();
  const webp = await sharp(source).webp({ lossless: true, effort: 6 }).toBuffer();

  const raw = await sharp(source).removeAlpha().raw().toBuffer();
  for (const [name, buf] of [['avif', avif], ['webp', webp]]) {
    const decoded = await sharp(buf).removeAlpha().toColourspace('srgb').raw({ depth: 'uchar' }).toBuffer();
    let max = 0;
    let sum = 0;
    for (let i = 0; i < raw.length; i++) {
      const d = Math.abs(raw[i] - decoded[i]);
      if (d > max) max = d;
      sum += d;
    }
    const file = resolve(root, `public/smoke-poster.${name}`);
    await writeFile(file, buf);
    console.log(`${name}: ${(buf.length / 1024).toFixed(1)} KB, max error ${max}/255, mean ${(sum / raw.length).toFixed(3)}`);
  }

  await writeFile(
    resolve(root, 'src/lib/smoke-poster.ts'),
    `// Generated by scripts/render-smoke-poster.mjs — do not edit by hand.\n` +
    `// Fingerprint of the shader + LUT that public/smoke-poster.{avif,webp} were rendered from.\n` +
    `export const SMOKE_POSTER_FINGERPRINT = '${fingerprint}';\n`,
  );
  console.log(`fingerprint ${fingerprint}`);
} finally {
  await browser?.close();
  await server.close();
  await rm(resolve(root, PAGE), { force: true });
}
// Fail loudly if an output went missing.
await Promise.all(['public/smoke-poster.avif', 'public/smoke-poster.webp', 'src/lib/smoke-poster.ts'].map((f) => stat(resolve(root, f))));
